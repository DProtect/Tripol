package core

// RAX=stable handle, RCX=needle. Search the current backing after evaluating
// arguments. Removing a value removes only its first matching occurrence.
func(c *compiler) findList(elem string,remove bool){
 a:=c.a
 loop,found,missing,done:=a.fresh(),a.fresh(),a.fresh(),a.fresh()
 a.emit(0x50,0x51,0x6a,0)
 a.label(loop)
 a.emit(0x48,0x8b,0x0c,0x24,0x48,0x8b,0x54,0x24,16,0x48,0x8b,0x52,8,0x48,0x3b,0x0a)
 a.j(0x83,missing)
 a.emit(0x48,0x8b,0x44,0xca,8)
 if elem=="string"{
  a.emit(0x48,0x8b,0x4c,0x24,8);a.call("streq");a.emit(0x48,0x85,0xc0);a.j(0x85,found)
 }else{a.emit(0x48,0x3b,0x44,0x24,8);a.j(0x84,found)}
 a.emit(0x48,0xff,0x04,0x24);a.jmp(loop)
 a.label(found)
 a.emit(0x59,0x5a,0x58)
 if remove{a.call("list_remove")}
 a.imm(1);a.jmp(done)
 a.label(missing);a.emit(0x48,0x83,0xc4,24);a.imm(0)
 a.label(done)
}

// Stable in-place insertion sort, bounded to 4096 entries. No allocations
// and no calls to user code. String ordering is unsigned byte lexicographic.
func(c *compiler) sortList(elem string){
 a:=c.a
 outer,inner,place,done,greater:=a.fresh(),a.fresh(),a.fresh(),a.fresh(),a.fresh()
 a.emit(0x48,0x8b,0x40,8,0x48,0x81,0x38,0,16,0,0);a.j(0x87,"bounds")
 // [rsp]=j, +8=key, +16=i, +24=backing.
 a.emit(0x50,0x6a,1,0x6a,0,0x6a,0)
 a.label(outer)
 a.emit(0x48,0x8b,0x4c,0x24,16,0x48,0x8b,0x54,0x24,24,0x48,0x3b,0x0a);a.j(0x83,done)
 a.emit(0x48,0x8b,0x44,0xca,8,0x48,0x89,0x44,0x24,8,0x48,0x89,0x0c,0x24)
 a.label(inner)
 a.emit(0x48,0x8b,0x0c,0x24,0x48,0x85,0xc9);a.j(0x84,place)
 a.emit(0x48,0x8b,0x54,0x24,24,0x48,0x8b,0x04,0xca)
 if elem=="string"{
  a.emit(0x48,0x8b,0x4c,0x24,8)
  // Compare strings in registers RAX and RCX; RDX contains only a byte.
  cmp:=a.fresh();a.label(cmp)
  a.emit(0x0f,0xb6,0x10,0x3a,0x11);a.j(0x87,greater);a.j(0x82,place)
  a.emit(0x84,0xd2);a.j(0x84,place)
  a.emit(0x48,0xff,0xc0,0x48,0xff,0xc1);a.jmp(cmp)
 }else{
  a.emit(0x48,0x3b,0x44,0x24,8);a.j(0x8f,greater);a.jmp(place)
 }
 a.label(greater)
 a.emit(0x48,0x8b,0x0c,0x24,0x48,0x8b,0x54,0x24,24,0x48,0x8b,0x04,0xca,0x48,0x89,0x44,0xca,8,0x48,0xff,0x0c,0x24)
 a.jmp(inner)
 a.label(place)
 a.emit(0x48,0x8b,0x0c,0x24,0x48,0x8b,0x54,0x24,24,0x48,0x8b,0x44,0x24,8,0x48,0x89,0x44,0xca,8,0x48,0xff,0x44,0x24,16)
 a.jmp(outer)
 a.label(done)
 a.emit(0x48,0x8b,0x44,0x24,24,0x48,0x8b,0x00,0x48,0x83,0xc4,32)
}
