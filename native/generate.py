# Maintainer-only: regenerate Go machine-code templates using GNU binutils.
import pathlib, subprocess, tempfile, re
root=pathlib.Path(__file__).resolve().parent
names={'print_float':'print:float','osalloc_linux':'osalloc:linux','osalloc_windows':'osalloc:windows','readbyte_linux':'readbyte:linux','readbyte_windows':'readbyte:windows'}
for helper in ('oscommit','game_open','game_running','game_present','game_key','game_close','ui_form','https_get','net_connect','net_send','net_shutdown','net_recv','net_close','file_open','file_chunk_read','file_chunk_write','file_close','clock_ms','sleep_ms'):
 for target in ('linux','windows'): names[helper+'_'+target]=helper+':'+target
with tempfile.TemporaryDirectory() as tmp:
 o=pathlib.Path(tmp)/'liberty.o'; b=pathlib.Path(tmp)/'code.bin'
 subprocess.run(['as','--64','-o',str(o),str(root/'liberty.S')],check=True)
 rel=subprocess.check_output(['objdump','-r',str(o)],text=True)
 sections=re.findall(r'\s+\.text\.(\w+)\s+',subprocess.check_output(['objdump','-h',str(o)],text=True))
 out=['// Code generated by native/generate.py; DO NOT EDIT.','package main','var libertyCode = map[string]nativeTemplate{']
 for s in sections:
  subprocess.run(['objcopy','-O','binary','-j','.text.'+s,str(o),str(b)],check=True)
  code=b.read_bytes(); fixes=[]
  m=re.search(r'RELOCATION RECORDS FOR \[\.text\.'+s+r'\]:\n(.*?)(?=\n\n|\Z)',rel,re.S)
  if m:
   for at,kind,label in re.findall(r'([0-9a-f]{16})\s+(R_X86_64_\w+)\s+(\S+)',m[1]):
    assert kind in ('R_X86_64_PC32','R_X86_64_PLT32') and label.endswith('-0x0000000000000004'),(kind,label)
    label=label.split('-')[0];label='iat:'+label[3:] if label.startswith('iat') else label
    fixes.append('{%d,"%s"}'%(int(at,16),label))
  out.append('"%s": {[]byte{%s}, []fix{%s}},'%(names.get(s,s),','.join(hex(x) for x in code),','.join(fixes)))
 out.append('}')
 (root.parent/'liberty_code.go').write_text('\n'.join(out)+'\n')
